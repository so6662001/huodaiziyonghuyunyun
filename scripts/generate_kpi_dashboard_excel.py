from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

THIN = Side(border_style="thin", color="CCCCCC")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
HEADER_FILL = PatternFill("solid", fgColor="1F4E78")
HEADER_FONT = Font(name="微软雅黑", size=11, bold=True, color="FFFFFF")
NORMAL_FONT = Font(name="微软雅黑", size=10)
BOLD_FONT = Font(name="微软雅黑", size=10, bold=True)
WRAP = Alignment(wrap_text=True, vertical="center", horizontal="center")
LEFT_WRAP = Alignment(wrap_text=True, vertical="center", horizontal="left")


def setup_sheet(ws, title, headers, widths):
    ws["A1"] = title
    ws["A1"].font = Font(name="微软雅黑", size=14, bold=True, color="1F4E78")
    ws.merge_cells(f"A1:{get_column_letter(len(headers))}1")
    ws.append([])
    ws.append(headers)
    for cell in ws[3]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = WRAP
        cell.border = BORDER
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def add_data_rows(ws, rows, start_row=4):
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=start_row, max_row=ws.max_row, min_col=1, max_col=len(rows[0])):
        for cell in row:
            cell.font = NORMAL_FONT
            cell.alignment = LEFT_WRAP
            cell.border = BORDER


